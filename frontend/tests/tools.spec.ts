import { test, expect } from '@playwright/test';
import crypto from 'node:crypto';
test('discover real MCP tools, invoke a read, and reject a proposed write', async ({ page }) => {
  test.setTimeout(120000);
  await page.goto('/');
  await page.getByRole('button', { name: 'Create a workspace' }).click();
  await page.getByLabel('Your name').fill('Tool Workbench QA');
  await page.getByLabel('Workspace name').fill('MCP browser verification');
  await page.getByLabel('Email address').fill(`tools-${crypto.randomUUID()}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill(crypto.randomBytes(24).toString('base64url'));
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Workspace overview' })).toBeVisible();
  await page.getByRole('link', { name: 'MCP connections', exact: true }).click();
  const analytics = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Analytics MCP', exact: true }) });
  await analytics.getByRole('button', { name: 'Discover tools', exact: true }).click();
  await expect(analytics.getByText('connected', { exact: true })).toBeVisible();
  await page.getByLabel('Discovered tool').selectOption('get_model_metrics');
  await page.getByRole('button', { name: 'Run read tool', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Execution history' })).toBeVisible();
  await expect(page.getByText('analytics / get_model_metrics', { exact: true })).toBeVisible();
  const github = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Github MCP', exact: true }) });
  await github.getByRole('button', { name: 'Discover tools', exact: true }).click();
  await expect(github.getByText('connected', { exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: 'Server', exact: true }).selectOption('github');
  await page.getByLabel('Discovered tool').selectOption('create_issue');
  await page.getByLabel('Arguments (JSON)').fill(JSON.stringify({ title: 'Browser approval verification', body: 'This is a local synthetic action proposed for review, then rejected by the user.' }));
  await page.getByRole('button', { name: 'Request approval', exact: true }).click();
  await expect(page.getByText('Approval requested. Review the exact payload on the Approvals page before any write can execute.')).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '../docs/screenshots/tools.png', fullPage: true });
  await page.getByRole('link', { name: 'Approvals', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Approval inbox' })).toBeVisible();
  await expect(page.getByText('pending', { exact: true })).toBeVisible();
  await page.screenshot({ path: '../docs/screenshots/approvals.png', fullPage: true });
  await page.getByRole('button', { name: 'Reject', exact: true }).click();
  await expect(page.getByText('rejected', { exact: true })).toBeVisible();
});
