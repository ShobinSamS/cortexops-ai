import { test, expect } from '@playwright/test';
import crypto from 'node:crypto';

test('real synthetic investigation, live progress, graph and PDF export', async ({ page }) => {
  test.skip(process.env.E2E_LLM !== '1', 'Set E2E_LLM=1 for the real CPU-model end-to-end workflow.');
  test.setTimeout(1200000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Create a workspace' }).click();
  await page.getByLabel('Your name').fill('Investigation QA');
  await page.getByLabel('Workspace name').fill('CortexOps demonstration');
  await page.getByLabel('Email address').fill(`investigation-${crypto.randomUUID()}@example.test`);
  await page.getByLabel('Password', { exact: true }).fill(crypto.randomBytes(24).toString('base64url'));
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await page.getByRole('button', { name: 'Load synthetic dataset' }).click();
  await expect(page.getByText('Dataset ready. Create an investigation to begin.')).toBeVisible({ timeout: 60000 });
  await page.getByRole('link', { name: 'Knowledge base', exact: true }).click();
  await expect(page.getByText('indexed', { exact: true })).toHaveCount(6, { timeout: 240000 });
  await page.getByRole('link', { name: 'Knowledge graph', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Connected evidence', exact: true })).toBeVisible();
  await expect(page.locator('.graph-node').first()).toBeVisible();
  await page.screenshot({ path: '../docs/screenshots/graph.png', fullPage: true });
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await page.screenshot({ path: '../docs/screenshots/overview-populated.png', fullPage: true });
  await page.getByRole('link', { name: 'New investigation' }).click();
  await page.getByLabel('Investigation title').fill('Document verification accuracy regression');
  await page.getByLabel('What would you like to investigate?').fill('Investigate why document verification accuracy dropped from 98% to 91% after deployment v2.3. Compare preprocessing, source mix, and model weights using the evidence.');
  await page.getByRole('button', { name: 'Create investigation', exact: true }).click();
  await page.getByRole('button', { name: 'Start investigation', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Agent execution graph' })).toBeVisible();
  await expect(page.getByText('Live socket connected', { exact: true })).toBeVisible({ timeout: 30000 });
  await page.screenshot({ path: '../docs/screenshots/execution-live.png', fullPage: true });
  await expect(page.getByRole('link', { name: 'Open evidence-backed report' })).toBeVisible({ timeout: 900000 });
  await page.screenshot({ path: '../docs/screenshots/execution.png', fullPage: true });
  await page.reload();
  await expect(page.getByRole('link', { name: 'Open evidence-backed report' })).toBeVisible();
  await page.getByRole('link', { name: 'Open evidence-backed report' }).click();
  await expect(page.getByRole('heading', { name: 'Verified observations', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: /nearest|interpol|resampl/i }).first()).toBeVisible();
  await page.screenshot({ path: '../docs/screenshots/report.png', fullPage: true });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export PDF', exact: true }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/cortexops-.*\.pdf$/);
  await download.saveAs('../output/pdf/browser-investigation-report.pdf');
  expect(errors).toEqual([]);
});
